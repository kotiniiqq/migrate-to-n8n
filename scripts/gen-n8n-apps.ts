/** Write src/map/n8n-apps.ts: the n8n app nodes (not core nodes) that both targeted n8n versions have,
 *  with the shared typeVersion. Only names and version numbers are kept.
 *
 *   npm run n8n-types && npx tsx scripts/gen-n8n-apps.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { CATALOGS, catalogDir } from './fetch-n8n-types.ts';

interface Desc { name: string; displayName: string; version: number | number[]; codex?: { categories?: string[] } }

const read = (n8n: string) => {
  const c = CATALOGS.find((x) => x.n8n === n8n)!;
  return JSON.parse(readFileSync(join(catalogDir('n8n-nodes-base', c.packages['n8n-nodes-base']), 'nodes.json'), 'utf8')) as Desc[];
};

const versions = (list: Desc[]) => {
  const m = new Map<string, { displayName: string; versions: Set<number>; core: boolean }>();
  for (const d of list) {
    const e = m.get(d.name) ?? { displayName: d.displayName, versions: new Set<number>(), core: false };
    for (const v of Array.isArray(d.version) ? d.version : [d.version]) e.versions.add(v);
    if (d.codex?.categories?.includes('Core Nodes')) e.core = true;
    m.set(d.name, e);
  }
  return m;
};

const [a, b] = CATALOGS.map((c) => versions(read(c.n8n)));
const rows: string[] = [];
for (const [name, e] of [...a].sort(([x], [y]) => x.localeCompare(y))) {
  const other = b.get(name);
  if (e.core || !other) continue;
  const shared = [...e.versions].filter((v) => other.versions.has(v));
  if (!shared.length) continue;
  rows.push(`  ['${name}', ${JSON.stringify(e.displayName)}, ${Math.max(...shared)}],`);
}
writeFileSync('src/map/n8n-apps.ts', [
  '/** n8n app nodes available in both targeted n8n versions: [name, display name, typeVersion].',
  ' *  Generated by scripts/gen-n8n-apps.ts; do not edit by hand. */',
  'export const N8N_APPS: ReadonlyArray<readonly [string, string, number]> = [',
  ...rows,
  '];',
  '',
].join('\n'));
console.log(`${rows.length} app nodes`);
